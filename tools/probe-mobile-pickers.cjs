const { chromium } = require('playwright');
const BASE='http://43.128.145.141/dms';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const ctx=await browser.newContext({viewport:{width:393,height:852},isMobile:true,hasTouch:true,deviceScaleFactor:2});
 const page=await ctx.newPage();
 page.on('console',m=>console.log('CONSOLE',m.type(),m.text()));
 page.on('response',async r=>{if(r.status()>=400)console.log('NET',r.status(),r.request().method(),r.url(),(await r.text().catch(()=>'')).slice(0,120))});
 await page.goto(BASE+'/mobile/login',{waitUntil:'domcontentloaded'});
 await page.waitForTimeout(1000);
 await page.locator('.van-field').filter({hasText:'租户'}).locator('input').fill('default');
 await page.locator('.van-field').filter({hasText:'账号'}).locator('input').fill('sys_admin');
 await page.locator('input[type=password]').first().fill('Dms@123456');
 await page.getByRole('button',{name:/登\s*录/}).click();
 await page.waitForURL(u=>!u.pathname.includes('/login'),{timeout:15000}).catch(()=>{});
 await page.waitForTimeout(2000);
 console.log('url',page.url());
 await page.goto(BASE+'/mobile/surgery-reports/create',{waitUntil:'domcontentloaded'});
 await page.waitForTimeout(2500);
 console.log('before', (await page.locator('body').innerText()).slice(0,500));
 const field=page.locator('.van-field').filter({hasText:'经销商'}).first();
 console.log('field html', await field.evaluate(e=>e.outerHTML.slice(0,800)).catch(e=>e.message));
 await field.click({timeout:5000});
 await page.waitForTimeout(1500);
 console.log('popups', await page.locator('.van-popup').count());
 console.log('picker columns', await page.locator('.van-picker-column').count());
 console.log('picker items', await page.locator('.van-picker-column__item').count());
 console.log('visible popup html', await page.locator('.van-popup:visible').first().evaluate(e=>e.outerHTML.slice(0,2000)).catch(e=>'NO:'+e.message));
 await page.screenshot({path:'D:/Workspace/TRAE/DMS/automation_test/v4-browser-results/probe-mobile-picker.png',fullPage:true});
 await browser.close();
})();
